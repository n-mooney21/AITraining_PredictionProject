"""#2. Data Preperation

"""

#Cleaning up Data
df['bytes_received'] = df['bytes_received'].fillna(df['bytes_received'].median())
df['signal_strength'] = df['signal_strength'].fillna(df['signal_strength'].median())

df['protocol'] = df['protocol'].fillna(df['protocol'].mode()[0])

#Adding New Features to the Dataset
df['total_traffic'] = df['bytes_sent'] + df['bytes_received']

df['failure_ratio'] = df['failed_logins'] / (df['login_attempts'] + 1)

#Encoding the Data

from sklearn.preprocessing import LabelEncoder, StandardScaler

le = LabelEncoder()
df['attack_category'] = le.fit_transform(df['attack_category'])

df_model = df.drop(columns=['packet_session_id'])

df_model = pd.get_dummies(df_model)

scaler = StandardScaler()

"""#3. Training the AI"""

from sklearn.model_selection import train_test_split

X = df_model.drop(columns=['attack_category', 'avg_packet_size'])
y_class = df_model['attack_category']
y_reg = df_model['avg_packet_size']

X_train, X_test, y_train_class, y_test_class = train_test_split(X, y_class, test_size=0.2, random_state=42)

X_train, X_test, y_train_reg, y_test_reg = train_test_split(X, y_reg, test_size=0.2, random_state=42)

from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_squared_error, r2_score

reg_model = RandomForestRegressor(n_estimators=100, random_state=42)
reg_model.fit(X_train, y_train_reg)
y_pred_reg = reg_model.predict(X_test)

print(mean_squared_error(y_test_reg, y_pred_reg))
print(r2_score(y_test_reg, y_pred_reg))

from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import classification_report, confusion_matrix

clf_model = RandomForestClassifier(n_estimators=100, random_state=42)
clf_model.fit(X_train, y_train_class)
y_pred_class = clf_model.predict(X_test)

print(confusion_matrix(y_test_class, y_pred_class))
print(classification_report(y_test_class, y_pred_class))

from sklearn.model_selection import cross_val_score

cv_scores = cross_val_score(clf_model, X, y_class, cv=5)
print(cv_scores.mean())